// Generates every instance-derived file from instance/ (or instance.example/):
//   wrangler.jsonc, src/generated/instance.ts, public/instance/{config.js,categories.css,theme.css,assets/}
// Usage: node scripts/build-instance.mjs [--root <dir>]   (runs automatically before dev, test, typecheck, deploy)
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { InstanceError, LOCALES, enabledCategories, loadInstance, publicConfig, renderWrangler, resolvePolicy } from "./lib/instance.mjs";

const args = process.argv.slice(2);
const rootArg = args.indexOf("--root");
const root = resolve(rootArg >= 0 ? args[rootArg + 1] : join(dirname(fileURLToPath(import.meta.url)), ".."));

export function buildInstance(root) {
  const { dir, config, isExample } = loadInstance(root);

  const overrides = {};
  for (const loc of LOCALES) {
    const f = join(dir, `strings.${loc}.json`);
    if (existsSync(f)) overrides[loc] = JSON.parse(readFileSync(f, "utf8"));
  }

  const header = "// GENERATED by scripts/build-instance.mjs from the instance folder. Do not edit.\n";
  const template = readFileSync(join(root, "wrangler.template.jsonc"), "utf8");
  writeFileSync(join(root, "wrangler.jsonc"), header + renderWrangler(template, config));

  mkdirSync(join(root, "src", "generated"), { recursive: true });
  const categories = enabledCategories(config);
  const serverPart = { app: config.app, categories, policy: resolvePolicy(config) };
  writeFileSync(
    join(root, "src", "generated", "instance.ts"),
    `${header}export const INSTANCE = ${JSON.stringify(serverPart, null, 2)} as const;\n`,
  );

  const out = join(root, "public", "instance");
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  writeFileSync(join(out, "config.js"), `${header}export default ${JSON.stringify(publicConfig(config, overrides), null, 2)};\n`);
  const catVars = [
    ...categories.project.map((c) => `  --cat-p-${c.key}: ${c.color};`),
    ...categories.workpackage.map((c) => `  --cat-w-${c.key}: ${c.color};`),
  ];
  writeFileSync(join(out, "categories.css"), `/* GENERATED from instance.config.json categories. */\n:root {\n${catVars.join("\n")}\n}\n`);
  if (existsSync(join(dir, "theme.css"))) cpSync(join(dir, "theme.css"), join(out, "theme.css"));
  if (existsSync(join(dir, "assets"))) cpSync(join(dir, "assets"), join(out, "assets"), { recursive: true });

  return { dir, isExample, files: readdirSync(out) };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const r = buildInstance(root);
    console.log(`instance: ${r.dir}${r.isExample ? " (example)" : ""}`);
  } catch (e) {
    if (e instanceof InstanceError) {
      console.error(e.message);
      process.exit(1);
    }
    throw e;
  }
}
