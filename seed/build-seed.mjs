// Builds seed/seed.sql from the instance seed (instance/seed.json, else instance.example/seed.json).
// The seed is meant to run once, on an empty database, right after the migrations.
// Usage: node seed/build-seed.mjs   (runs automatically before npm test)
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { instanceDir } from "../scripts/lib/instance.mjs";

const ACTOR = "seed";
const MAX_STATEMENT_BYTES = 100_000; // D1 SQL statement limit

const q = (v) => (v === null || v === undefined ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const ts = { sql: "strftime('%Y-%m-%dT%H:%M:%fZ','now')" };
/** Deterministic UUID-shaped id, so rebuilding the seed gives the same file. */
function sid(key) {
  const h = createHash("sha256").update(`project-tracker-seed:${key}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20, 32)}`;
}

/** Writes <root>/seed/seed.sql from the instance seed.json; returns the path and the project count. */
export function buildSeed(root) {
  const seedPath = join(instanceDir(root), "seed.json");
  const outPath = join(root, "seed", "seed.sql");
  const seed = existsSync(seedPath) ? JSON.parse(readFileSync(seedPath, "utf8")) : { projects: [] };
  const out = ["-- Generated by seed/build-seed.mjs from the instance seed.json; do not edit by hand.", ""];
  const insert = (table, row) => {
    const cols = Object.keys(row);
    const vals = cols.map((c) => (row[c] && typeof row[c] === "object" && "sql" in row[c] ? row[c].sql : q(row[c])));
    out.push(`INSERT INTO ${table} (${cols.join(", ")}) VALUES (${vals.join(", ")});`);
  };
  const event = (project_id, entity, entity_id, summary) =>
    insert("event", { ts, actor: ACTOR, project_id, entity, entity_id, action: "create", summary, diff_json: null });

  function insertWp(p, w, parentId, sort) {
    insert("workpackage", {
      id: w.id,
      project_id: p.id,
      parent_id: parentId,
      title: w.title,
      description_md: w.description_md ?? null,
      status: w.status ?? "todo",
      blocked_by: null,
      progress: w.progress ?? 0,
      weight: w.weight ?? 1,
      start_date: w.start_date ?? null,
      end_date: w.end_date ?? null,
      depends_on: null,
      sort,
      category: w.category ?? null,
      human: null,
      version: 1,
      created_at: ts,
      updated_at: ts,
    });
    (w.children ?? []).forEach((c, i) => insertWp(p, c, w.id, i));
  }

  for (const p of seed.projects) {
    out.push(`-- ${p.id}`);
    insert("project", {
      id: p.id,
      title: p.title,
      summary: p.summary ?? null,
      description_md: p.description_md ?? null,
      status: p.status ?? "active",
      origin: "manual",
      repo_url: p.repo_url ?? null,
      local_path: null,
      context_file: null,
      session_id: null,
      start_date: p.start_date ?? null,
      target_date: p.target_date ?? null,
      progress_mode: "derived",
      progress_manual: null,
      tags: JSON.stringify(p.tags ?? []),
      category: p.category ?? null,
      version: 1,
      created_at: ts,
      updated_at: ts,
    });
    event(p.id, "project", p.id, p.title);
    (p.workpackages ?? []).forEach((w, i) => insertWp(p, w, null, i));

    (p.milestones ?? []).forEach((m, i) => {
      insert("milestone", {
        id: m.id,
        project_id: p.id,
        workpackage_id: null,
        title: m.title,
        description_md: m.description_md ?? null,
        due_date: m.due_date ?? null,
        reached_at: null,
        sort: i,
        version: 1,
        created_at: ts,
        updated_at: ts,
      });
      for (const role of ["requires", "unlocks"])
        for (const wp of m[role] ?? []) insert("milestone_link", { milestone_id: m.id, workpackage_id: wp, role });
    });

    (p.context ?? []).forEach((d, i) => {
      const id = sid(`ctx:project:${p.id}:${d.slug}`);
      insert("context_doc", {
        id,
        project_id: p.id,
        owner_kind: "project",
        owner_id: p.id,
        title: d.title,
        slug: d.slug,
        source: "claude",
        filename: null,
        content_md: d.content_md,
        pinned: d.pinned ? 1 : 0,
        sort: i,
        bytes: Buffer.byteLength(d.content_md, "utf8"),
        version: 1,
        created_at: ts,
        updated_at: ts,
        created_by: ACTOR,
        updated_by: ACTOR,
      });
      event(p.id, "context_doc", id, `project:${p.id}/${d.slug}`);
    });
    out.push("");
  }

  for (const stmt of out)
    if (Buffer.byteLength(stmt, "utf8") > MAX_STATEMENT_BYTES)
      throw new Error(`statement over ${MAX_STATEMENT_BYTES} bytes: ${stmt.slice(0, 80)}`);
  const sql = out.join("\n");
  writeFileSync(outPath, sql, "utf8");
  return { path: outPath, projects: seed.projects.length };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const r = buildSeed(join(dirname(fileURLToPath(import.meta.url)), ".."));
  console.log(`seed: ${r.path} (${r.projects} project${r.projects === 1 ? "" : "s"})`);
}
